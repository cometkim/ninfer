#!/usr/bin/env bash
set -euo pipefail

# Model-card quality gate: GPQA-Diamond + AIME26 against one registered serving
# profile (thinking, MTP3 full head, INT8 KV, native 262,144 context), fresh
# seeds per round. Windows-native: Git Bash + build-ninja apps + the Windows
# eval venv.
#
# usage: eval/run_card_quality.sh <artifact-path> <label> [kv-dtype] [seed ...]
#   kv-dtype: int8 (default) or hq-e8-2b - the codec A/B axis; the model id and
#   generated configs carry the dtype so runs and results stay distinguishable.
#   default seeds: 42 43 44 (one independent round each)

repo_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
server_bin="${repo_dir}/build-ninja/apps/ninfer-serve.exe"
eval_python="${repo_dir}/eval/.venv/Scripts/python.exe"
log_dir="${repo_dir}/eval/server-logs"
port=18081

if [[ $# -lt 2 ]]; then
    echo "usage: $0 <artifact-path> <label> [seed ...]" >&2
    exit 2
fi
artifact="$1"
label="$2"
kv="int8"
if [[ "${3:-}" == "int8" || "${3:-}" == "hq-e8-2b" ]]; then
    kv="$3"
    shift
fi
shift 2
seeds=("$@")
if [[ ${#seeds[@]} -eq 0 ]]; then
    seeds=(42 43 44)
fi
kv_suffix=""
[[ "${kv}" == "hq-e8-2b" ]] && kv_suffix="-hq"
model_id="qwen3.8-27b-${label}-card${kv_suffix}"

for required_file in "${server_bin}" "${artifact}" "${eval_python}"; do
    if [[ ! -f "${required_file}" ]]; then
        echo "missing required file: ${required_file}" >&2
        exit 1
    fi
done
if ! command -v curl >/dev/null 2>&1; then
    echo "curl is required for the server health check" >&2
    exit 1
fi

mkdir -p -- "${log_dir}"
run_stamp="$(date -u +%Y%m%dT%H%M%SZ)"
server_log="${log_dir}/card-${label}-${run_stamp}.server.log"
request_log="${log_dir}/card-${label}-${run_stamp}.requests.jsonl"

if curl --fail --silent --show-error --max-time 2 "http://127.0.0.1:${port}/health" >/dev/null 2>&1; then
    echo "port ${port} already has a healthy service; stop it before running this script" >&2
    exit 1
fi

server_pid=""
cleanup() {
    if [[ -n "${server_pid}" ]] && kill -0 "${server_pid}" 2>/dev/null; then
        kill -TERM "${server_pid}"
        wait "${server_pid}" || true
    fi
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

# The registered card lane: native 262,144-token context on INT8 KV with MTP3
# at the full output head. Vision stays off so its fixed allocations do not
# shrink the KV pool behind long thinking tails.
"${server_bin}" "${artifact}" \
    --host 127.0.0.1 \
    --port "${port}" \
    --model-id "${model_id}" \
    --max-context 262144 \
    --kv-capacity auto \
    --max-concurrency 2 \
    --max-pending-requests 2 \
    --pending-timeout-ms 86400000 \
    --prefill-chunk 1024 \
    --kv-dtype "${kv}" \
    --spec mtp \
    --draft-tokens 3 \
    --request-log-jsonl "${request_log}" \
    >"${server_log}" 2>&1 &
server_pid=$!

ready=0
for ((attempt = 1; attempt <= 180; ++attempt)); do
    if curl --fail --silent --show-error --max-time 2 \
        "http://127.0.0.1:${port}/health" >/dev/null 2>&1; then
        ready=1
        break
    fi
    if ! kill -0 "${server_pid}" 2>/dev/null; then
        wait "${server_pid}" || true
        echo "ninfer-serve exited before becoming ready; see ${server_log}" >&2
        exit 1
    fi
    sleep 1
done
if [[ "${ready}" -ne 1 ]]; then
    echo "ninfer-serve did not become ready within 180 seconds; see ${server_log}" >&2
    exit 1
fi
echo "server log: ${server_log}"
echo "request log: ${request_log}"

for seed in "${seeds[@]}"; do
    config="${repo_dir}/eval/runs-card/${label}-seed${seed}.yaml"
    mkdir -p -- "${repo_dir}/eval/runs-card"
    cat >"${config}" <<CONFIG
schema_version: 1

# Generated by eval/run_card_quality.sh for artifact label '${label}' (round seed ${seed}).
# Registered profile: thinking on, temperature 0.6, top_p 0.95, top_k 20, 0-shot,
# rule scoring; server = MTP3 full head, INT8 KV, native 262,144 context.

targets:
  card_api:
    protocol: openai_chat
    base_url: http://127.0.0.1:${port}/v1
    model: ${model_id}
    max_concurrency: 2
    request:
      timeout_seconds: 86400
      retries: 2
      retry_interval_seconds: 10

suites:
  card_quality:
    jobs:
      - id: aime26_seed${seed}
        backend: evalscope
        dataset: aime26
        target: card_api
        max_concurrency: 2
        generation:
          temperature: 0.6
          top_p: 0.95
          top_k: 20
          presence_penalty: 0.0
          frequency_penalty: 0.0
          # At C=2, two full budgets use 245,760 of the 262,144-token envelope.
          max_tokens: 122880
          seed: ${seed}
          extra_body:
            enable_thinking: true
            min_p: 0.0
        backend_args:
          judge_strategy: rule
          dataset_hub: modelscope

      - id: gpqa_diamond_seed${seed}
        backend: evalscope
        dataset: gpqa_diamond
        target: card_api
        max_concurrency: 1
        generation:
          temperature: 0.6
          top_p: 0.95
          top_k: 20
          presence_penalty: 0.0
          frequency_penalty: 0.0
          # C=1 keeps the 245,760-token output budget inside the envelope.
          max_tokens: 245760
          seed: ${seed}
          extra_body:
            enable_thinking: true
            min_p: 0.0
        backend_args:
          few_shot_num: 0
          judge_strategy: rule
          dataset_hub: modelscope

runtime:
  max_parallel_jobs: 1
  runs_dir: eval/runs
  progress:
    enabled: true
    refresh_seconds: 1
    heartbeat_seconds: 900
  samples:
    retention: all
CONFIG

    echo "=== round seed ${seed}: AIME26 + GPQA-Diamond on ${label} ==="
    PYTHONPATH="${repo_dir}/eval" "${eval_python}" -m ninfer_eval run \
        --config "${config}" --suite card_quality
done
